/**
 * Generates `docs/schema-audit.sql`: one query that says what a database is
 * missing.
 *
 * Applying the bootstrap by pasting it into a SQL editor can truncate, and
 * that fails silently — the statements that arrived all succeed, and what is
 * lost is the end of the file. The symptom turns up later as a page that will
 * not load, naming one column. Fixing that one column and reloading finds the
 * next, which is a slow way to learn what a whole failed paste cost.
 *
 * This asks the question once: of every table and column the code expects,
 * which are absent? It reads the current Drizzle snapshot rather than a list
 * typed here, so it cannot drift from the schema it is checking.
 *
 * Read-only. It changes nothing and is safe on production.
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const metaDir = path.join(root, "drizzle/meta");

const snapshots = readdirSync(metaDir).filter(name => /^\d+_snapshot\.json$/.test(name)).sort();
if (!snapshots.length) throw new Error("No Drizzle snapshot found — run `pnpm drizzle-kit generate` first.");
const snapshot = JSON.parse(readFileSync(path.join(metaDir, snapshots.at(-1)), "utf-8"));

/*
 * One row per table, with its columns packed into a comma-separated string,
 * rather than one row per column.
 *
 * That is not tidiness. The first version of this file listed all 219 columns
 * on their own lines and came to 252 — and it was truncated on paste at line
 * 150, which is the exact failure it exists to diagnose. A file that cannot
 * survive being pasted is no use as a paste-in diagnostic. Packed, it is about
 * fifty lines and twenty-two of them are data.
 */
const tables = Object.values(snapshot.tables)
  .map(table => ({ name: table.name, columns: Object.values(table.columns).map(column => column.name).sort() }))
  .sort((a, b) => a.name.localeCompare(b.name));

const columnCount = tables.reduce((total, table) => total + table.columns.length, 0);
const quote = value => `'${String(value).replace(/'/g, "''")}'`;
const rows = tables
  .map(table => `    (${quote(table.name)}, ${quote(table.columns.join(","))})`)
  .join(",\n");

const sql = `-- NetLet schema audit — generated by scripts/build-schema-audit.mjs. Do not edit.
--
-- Answers one question: of everything the deployed code expects, what is this
-- database missing? Read-only; it changes nothing and is safe on production.
--
-- Run it in the Supabase SQL editor. **No rows returned is the good result.**
-- Any row names a table or column that is absent, which means the bootstrap was
-- applied only in part — usually a paste that was cut short. The fix is always
-- the same: run \`docs/supabase-bootstrap.sql\` again, in full, and check for its
-- "bootstrap complete" row at the end.
--
-- Expected: ${columnCount} columns across ${tables.length} tables.

WITH expected AS (
  SELECT
    packed.table_name,
    unnest(string_to_array(packed.columns, ',')) AS column_name
  FROM (VALUES
${rows}
  ) AS packed (table_name, columns)
)
SELECT
  e.table_name,
  e.column_name,
  CASE WHEN t.table_name IS NULL THEN 'whole table missing' ELSE 'column missing' END AS problem
FROM expected e
LEFT JOIN information_schema.columns c
  ON c.table_schema = 'public' AND c.table_name = e.table_name AND c.column_name = e.column_name
LEFT JOIN information_schema.tables t
  ON t.table_schema = 'public' AND t.table_name = e.table_name
WHERE c.column_name IS NULL
ORDER BY e.table_name, e.column_name;
`;

writeFileSync(path.join(root, "docs/schema-audit.sql"), sql);
console.log(`docs/schema-audit.sql — ${columnCount} columns across ${tables.length} tables, ${sql.split("\n").length} lines`);
