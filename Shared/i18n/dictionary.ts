export const messages: Record<LocaleCode, Record<ShopMessageKey, string>> = { en, ar };

/**
 * Words that arrive after the first download — the shop's later pages', added
 * by `laterMessages.ts` with the first page `lazyPage` fetches, and the
 * portal's, by `portalMessages.ts` as the portal's frame loads (and by the
 * server, the tests and the iOS export, which import both beside this file).
 */
const later: Record<LocaleCode, Record<string, string>> = { en: {}, ar: {} };

/** Adds words loaded after this module: `laterMessages.ts`' and `portalMessages.ts`'. */
export function addMessages(more: Record<LocaleCode, Record<string, string>>): void {
  for (const locale of LOCALES) Object.assign(later[locale], more[locale]);
}

/** A key's own string in one language, the shop's or a word added later. */
function own(locale: LocaleCode, key: MessageKey): string | undefined {
  return (messages[locale] as Record<string, string>)[key] ?? later[locale][key];
}

/**
 * Looks up a message and substitutes `{placeholders}`.
 *
 * Falls back to English rather than showing the raw key: a missing translation
 * should read as an untranslated word, not as `product.addToCart`.
 */
export function translate(
  locale: LocaleCode,
  key: MessageKey,
  values?: Record<string, string | number>,
): string {
  /* A counted sentence takes the form its number needs — six bands in Arabic
     (`plurals.ts`) — and the dictionary's own string otherwise. */
  const template = pluralForm(locale, key, values) ?? own(locale, key) ?? own("en", key) ?? key;
  if (!values) return template;
  return template.replace(/\{(\w+)\}(\.?)/g, (whole, name: string, stop: string) => {
    if (!(name in values)) return whole;
    const value = String(values[name]);
    /* A value that already ends on its own dot is not given the sentence's
       full stop as well: the dinar in Arabic is "د.ك.", and every sentence
       ending on an amount read "د.ك.." on the web and in the app. */
    return stop && endsOnDot(value) ? value : value + stop;
  });
}

/** Direction marks a formatter puts after a value, which hide its last character. */
const TRAILING_MARKS = /[‎‏؜⁦-⁩]+$/;

/** Whether a filled-in value ends on a dot of its own ("د.ك.", "etc."). */
export function endsOnDot(value: string): boolean {
  return value.replace(TRAILING_MARKS, "").endsWith(".");
}

/** Arabic is right-to-left; everything else here is not. */
export function directionFor(locale: LocaleCode): "rtl" | "ltr" {
  return locale === "ar" ? "rtl" : "ltr";
}

/**
 * Whether a string is one of this dictionary's keys.
 *
 * The server answers a failed sign-in with a key rather than a sentence, so the
 * shopper reads the refusal in their own language. Anything else — a Zod
 * validation message, a configuration error — is passed through untouched
 * rather than swallowed.
 */
export function isMessageKey(value: string): value is MessageKey {
  return value in en || value in later.en;
}
