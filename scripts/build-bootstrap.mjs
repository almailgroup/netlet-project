/**
 * Regenerates `docs/supabase-bootstrap.sql`.
 *
 * That file is the schema and the seed as one paste-able block, for setting a
 * database up from the Supabase dashboard with nothing installed. It has to
 * stay in step with `drizzle/*.sql` and `shared/commerce/departments.ts`, and
 * it had already drifted two migrations behind when it was only ever updated
 * by hand — which is the whole argument for this script existing.
 *
 * Run it after any schema change: `node scripts/build-bootstrap.mjs`.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");

/** Single-quote a SQL string literal. */
const quote = value => `'${value.replace(/'/g, "''")}'`;

const header = `-- NetLet — one-shot Supabase bootstrap.
--
-- Paste the whole file into the Supabase SQL Editor and run it. It creates
-- every table the app needs and seeds the departments and the house vendor.
--
-- This is the same schema \`pnpm db:push\` applies and the same rows
-- \`pnpm db:seed\` writes — it exists so a database can be set up from the
-- Supabase dashboard alone, with no local checkout and no Node installed.
--
-- Generated by scripts/build-bootstrap.mjs from drizzle/*.sql and
-- shared/commerce/departments.ts. Regenerate rather than hand-editing.
`;

const migrationsDir = path.join(root, "drizzle");
const migrations = readdirSync(migrationsDir).filter(name => name.endsWith(".sql")).sort();

const sections = migrations.map(name => {
  const body = readFileSync(path.join(migrationsDir, name), "utf-8")
    .split("--> statement-breakpoint")
    .map(statement => statement.trim())
    .filter(Boolean)
    .join("\n");
  return `\n-- ===== ${name} =====\n${body}\n`;
});

/* Read the departments out of the TypeScript rather than re-listing them:
   the point of the file living in `shared` is that there is one copy. */
const departmentsSource = readFileSync(path.join(root, "shared/commerce/departments.ts"), "utf-8");
const departments = [...departmentsSource.matchAll(
  /\{\s*slug:\s*"([^"]+)",\s*name:\s*"([^"]+)",\s*nameAr:\s*"([^"]+)",\s*position:\s*(\d+)\s*\}/g,
)].map(([, slug, name, nameAr, position]) => ({ slug, name, nameAr, position }));

if (departments.length === 0) {
  throw new Error("No departments parsed from shared/commerce/departments.ts — refusing to write an empty seed.");
}

const seed = `
-- ===== seed: departments and the house vendor =====
-- Mirrors \`pnpm db:seed\`. Safe to run again: both inserts skip a row that is
-- already there, so re-running after adding a department disturbs nothing.
--
-- Deliberately no products. A product needs a vendor to own it and a
-- department to be found in; the catalog itself is yours to add at /admin.

INSERT INTO categories (slug, name, name_ar, position) VALUES
${departments.map(d => `  (${quote(d.slug)}, ${quote(d.name)}, ${quote(d.nameAr)}, ${d.position})`).join(",\n")}
ON CONFLICT (slug) DO NOTHING;

-- NetLet sells its own stock as well as its vendors'. Something has to own a
-- product before a product can exist, so this vendor is that owner: approved,
-- auto-publishing (an admin reviewing their own listings teaches nothing), and
-- on zero commission because NetLet takes nothing from itself.
INSERT INTO vendors (slug, name, name_ar, status, auto_publish, commission_percent) VALUES
  ('netlet', 'NetLet', 'نتلت', 'approved', true, '0.00')
ON CONFLICT (slug) DO NOTHING;
`;

const out = path.join(root, "docs/supabase-bootstrap.sql");
writeFileSync(out, header + sections.join("") + seed);
console.log(`docs/supabase-bootstrap.sql — ${migrations.length} migrations, ${departments.length} departments`);
