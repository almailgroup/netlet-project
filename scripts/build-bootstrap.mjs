/**
 * Regenerates `docs/supabase-bootstrap.sql`.
 *
 * That file is the schema and the seed as one paste-able block, for setting a
 * database up from the Supabase dashboard with nothing installed. It has to
 * stay in step with `drizzle/*.sql` and `shared/commerce/departments.ts`, and
 * it had already drifted two migrations behind when it was only ever updated
 * by hand — which is the whole argument for this script existing.
 *
 * **The output is idempotent, and that is the point.** Written as plain
 * migrations it only worked on an empty database, so a database that was
 * behind needed somebody to work out *which* migrations it had missed and
 * paste exactly those — which is a diagnosis, made by hand, at the moment
 * something is already broken. Rewritten with IF NOT EXISTS (and a DO block
 * where Postgres offers no such clause), the answer to "my database is
 * behind" is always the same: run this file. Running it on a database that is
 * already current does nothing.
 *
 * Run it after any schema change: `node scripts/build-bootstrap.mjs`.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");

/** Single-quote a SQL string literal. */
const quote = value => `'${value.replace(/'/g, "''")}'`;

const header = `-- NetLet — one-shot Supabase bootstrap.
--
-- Paste the whole file into the Supabase SQL Editor and run it. It creates
-- every table the app needs and seeds the departments and the house vendor.
--
-- This is the same schema \`pnpm db:push\` applies and the same rows
-- \`pnpm db:seed\` writes — it exists so a database can be set up from the
-- Supabase dashboard alone, with no local checkout and no Node installed.
--
-- Safe to run more than once, and safe to run on a database that is only
-- part-way up to date: every statement skips what is already there. If a
-- page reports a missing column, running this whole file again is the fix.
--
-- Generated by scripts/build-bootstrap.mjs from drizzle/*.sql and
-- shared/commerce/departments.ts. Regenerate rather than hand-editing.
`;

const migrationsDir = path.join(root, "drizzle");
const migrations = readdirSync(migrationsDir).filter(name => name.endsWith(".sql")).sort();

/**
 * Makes one statement safe to run against a database that may already have it.
 *
 * Only six shapes appear across the migrations, which is why this is a
 * rewrite rather than a parser. Anything unrecognised is passed through
 * untouched and reported, so a new shape is noticed rather than silently
 * left non-idempotent.
 */
const unhandled = [];
function idempotent(statement) {
  const sql = statement.trim();

  if (/^CREATE TABLE "/.test(sql)) return sql.replace(/^CREATE TABLE /, "CREATE TABLE IF NOT EXISTS ");
  if (/^CREATE UNIQUE INDEX "/.test(sql)) return sql.replace(/^CREATE UNIQUE INDEX /, "CREATE UNIQUE INDEX IF NOT EXISTS ");
  if (/^CREATE INDEX "/.test(sql)) return sql.replace(/^CREATE INDEX /, "CREATE INDEX IF NOT EXISTS ");
  if (/^ALTER TABLE .+ ADD COLUMN /.test(sql)) return sql.replace(/ ADD COLUMN /, " ADD COLUMN IF NOT EXISTS ");

  // Dropping NOT NULL from a column that is already nullable is a no-op, so
  // this one is re-runnable as written. Named rather than left to the
  // fall-through, so it is a decision and not an oversight.
  if (/^ALTER TABLE .+ ALTER COLUMN .+ DROP NOT NULL/.test(sql)) return sql;

  /*
   * A rename is the one shape that is actively not re-runnable: run twice,
   * the old column is gone and Postgres errors. Guarded on the old column
   * still being there, it renames on a database that has not had it and does
   * nothing on one that has.
   */
  const rename = sql.match(/^ALTER TABLE "([^"]+)" RENAME COLUMN "([^"]+)" TO "([^"]+)"/);
  if (rename) {
    const [, table, from, to] = rename;
    return [
      "DO $$ BEGIN",
      "  IF EXISTS (SELECT 1 FROM information_schema.columns",
      `             WHERE table_schema = 'public' AND table_name = '${table}' AND column_name = '${from}') THEN`,
      `    ALTER TABLE "${table}" RENAME COLUMN "${from}" TO "${to}";`,
      "  END IF;",
      "END $$;",
    ].join("\n");
  }

  // Postgres has no IF NOT EXISTS for either of these, so swallow the
  // "already there" error and let every other error still fail the run.
  if (/^CREATE TYPE /.test(sql) || /^ALTER TABLE .+ ADD CONSTRAINT /.test(sql)) {
    const body = sql.replace(/;\s*$/, "");
    return `DO $$ BEGIN\n  ${body};\nEXCEPTION WHEN duplicate_object THEN NULL;\nEND $$;`;
  }

  unhandled.push(sql.split("\n")[0].slice(0, 80));
  return sql;
}

const sections = migrations.map(name => {
  const body = readFileSync(path.join(migrationsDir, name), "utf-8")
    .split("--> statement-breakpoint")
    .map(statement => statement.trim())
    .filter(Boolean)
    .map(idempotent)
    .join("\n");
  return `\n-- ===== ${name} =====\n${body}\n`;
});

/* Read the departments out of the TypeScript rather than re-listing them:
   the point of the file living in `shared` is that there is one copy. */
const departmentsSource = readFileSync(path.join(root, "shared/commerce/departments.ts"), "utf-8");
const departments = [...departmentsSource.matchAll(
  /\{\s*slug:\s*"([^"]+)",\s*name:\s*"([^"]+)",\s*nameAr:\s*"([^"]+)",\s*position:\s*(\d+)\s*\}/g,
)].map(([, slug, name, nameAr, position]) => ({ slug, name, nameAr, position }));

if (departments.length === 0) {
  throw new Error("No departments parsed from shared/commerce/departments.ts — refusing to write an empty seed.");
}

const seed = `
-- ===== seed: departments and the house vendor =====
-- Mirrors \`pnpm db:seed\`. Safe to run again: both inserts skip a row that is
-- already there, so re-running after adding a department disturbs nothing.
--
-- Deliberately no products. A product needs a vendor to own it and a
-- department to be found in; the catalog itself is yours to add at /admin.

INSERT INTO categories (slug, name, name_ar, position) VALUES
${departments.map(d => `  (${quote(d.slug)}, ${quote(d.name)}, ${quote(d.nameAr)}, ${d.position})`).join(",\n")}
ON CONFLICT (slug) DO NOTHING;

-- NetLet sells its own stock as well as its vendors'. Something has to own a
-- product before a product can exist, so this vendor is that owner: approved,
-- auto-publishing (an admin reviewing their own listings teaches nothing), and
-- on zero commission because NetLet takes nothing from itself.
INSERT INTO vendors (slug, name, name_ar, status, auto_publish, commission_percent) VALUES
  ('netlet', 'NetLet', 'نتلت', 'approved', true, '0.00')
ON CONFLICT (slug) DO NOTHING;
`;

const out = path.join(root, "docs/supabase-bootstrap.sql");
writeFileSync(out, header + sections.join("") + seed);
if (unhandled.length) {
  // Loud, because a statement that slipped through is a file that claims to
  // be re-runnable and is not.
  console.error(`\nNot made idempotent — teach idempotent() these shapes:`);
  for (const line of unhandled) console.error(`  ${line}`);
  process.exit(1);
}

console.log(`docs/supabase-bootstrap.sql — ${migrations.length} migrations, ${departments.length} departments, every statement idempotent`);
