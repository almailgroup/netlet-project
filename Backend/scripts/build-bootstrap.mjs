/**
 * Regenerates `docs/supabase-bootstrap.sql`.
 *
 * That file is the schema and the seed as one paste-able block, for setting a
 * database up from the Supabase dashboard with nothing installed. It has to
 * stay in step with `Backend/database/*.sql` and `Shared/commerce/departments.ts`, and
 * it had already drifted two migrations behind when it was only ever updated
 * by hand — which is the whole argument for this script existing.
 *
 * **The output is idempotent, and that is the point.** Written as plain
 * migrations it only worked on an empty database, so a database that was
 * behind needed somebody to work out *which* migrations it had missed and
 * paste exactly those — which is a diagnosis, made by hand, at the moment
 * something is already broken. Rewritten with IF NOT EXISTS (and a DO block
 * where Postgres offers no such clause), the answer to "my database is
 * behind" is always the same: run this file. Running it on a database that is
 * already current does nothing.
 *
 * Run it after any schema change: `node Backend/scripts/build-bootstrap.mjs`.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");

/** Single-quote a SQL string literal. */
const quote = value => `'${value.replace(/'/g, "''")}'`;

const header = `-- NetLet — one-shot Supabase bootstrap.
--
-- Paste the whole file into the Supabase SQL Editor and run it. It creates
-- every table the app needs and seeds the departments and the house vendor.
--
-- This is the same schema \`pnpm db:push\` applies and the same rows
-- \`pnpm db:seed\` writes — it exists so a database can be set up from the
-- Supabase dashboard alone, with no local checkout and no Node installed.
--
-- Safe to run more than once, and safe to run on a database that is only
-- part-way up to date: every statement skips what is already there. If a
-- page reports a missing column, running this whole file again is the fix.
--
-- It is also **all or nothing**. Everything below runs inside one transaction,
-- so a paste that gets cut short applies nothing at all rather than leaving a
-- database half-way up to date — which is the state that is hardest to
-- diagnose, because the schema then matches neither the old code nor the new.
-- Postgres runs DDL transactionally, and nothing here is one of the few
-- statements that cannot join a transaction, so this costs nothing.
--
-- Generated by Backend/scripts/build-bootstrap.mjs from Backend/database/*.sql and
-- Shared/commerce/departments.ts. Regenerate rather than hand-editing.

BEGIN;
`;

const migrationsDir = path.join(root, "Backend/database");
const migrations = readdirSync(migrationsDir).filter(name => name.endsWith(".sql")).sort();

/**
 * Makes one statement safe to run against a database that may already have it.
 *
 * Only a handful of shapes appear across the migrations, which is why this is a
 * rewrite rather than a parser. Anything unrecognised is passed through
 * untouched and reported, so a new shape is noticed rather than silently
 * left non-idempotent.
 */
const unhandled = [];
function idempotent(statement) {
  const sql = statement.trim();

  if (/^CREATE TABLE "/.test(sql)) return sql.replace(/^CREATE TABLE /, "CREATE TABLE IF NOT EXISTS ");
  if (/^CREATE UNIQUE INDEX "/.test(sql)) return sql.replace(/^CREATE UNIQUE INDEX /, "CREATE UNIQUE INDEX IF NOT EXISTS ");
  if (/^CREATE INDEX "/.test(sql)) return sql.replace(/^CREATE INDEX /, "CREATE INDEX IF NOT EXISTS ");
  if (/^ALTER TABLE .+ ADD COLUMN /.test(sql)) return sql.replace(/ ADD COLUMN /, " ADD COLUMN IF NOT EXISTS ");
  // Dropping an index a fresh database never had is the ordinary case here:
  // the file is one paste for a database at any version.
  if (/^DROP INDEX "/.test(sql)) return sql.replace(/^DROP INDEX /, "DROP INDEX IF EXISTS ");
  // Same for a column: a database provisioned after the drop never had it, and
  // one provisioned before is exactly who is pasting this. The column's own
  // indexes go with it, so no DROP INDEX is needed beside this.
  if (/^ALTER TABLE .+ DROP COLUMN /.test(sql)) return sql.replace(/ DROP COLUMN /, " DROP COLUMN IF EXISTS ");
  // A table goes the same way: one provisioned after the drop never had it.
  if (/^DROP TABLE "/.test(sql)) return sql.replace(/^DROP TABLE /, "DROP TABLE IF EXISTS ");
  // Deleting rows that may already be gone deletes nothing the second time.
  // Only ever written by hand into a migration, and only to clear rows a
  // removed feature left behind.
  if (/^DELETE FROM "/.test(sql)) return sql;

  // Dropping a NOT NULL that is already gone, or a default that is already
  // gone, is a no-op in Postgres, so both are re-runnable as written. Named
  // rather than left to the fall-through, so each is a decision and not an
  // oversight.
  if (/^ALTER TABLE .+ ALTER COLUMN .+ DROP (NOT NULL|DEFAULT)/.test(sql)) return sql;

  /*
   * A rename is the one shape that is actively not re-runnable: run twice,
   * the old column is gone and Postgres errors. Guarded on the old column
   * still being there, it renames on a database that has not had it and does
   * nothing on one that has.
   */
  const rename = sql.match(/^ALTER TABLE "([^"]+)" RENAME COLUMN "([^"]+)" TO "([^"]+)"/);
  if (rename) {
    const [, table, from, to] = rename;
    return [
      "DO $$ BEGIN",
      "  IF EXISTS (SELECT 1 FROM information_schema.columns",
      `             WHERE table_schema = 'public' AND table_name = '${table}' AND column_name = '${from}') THEN`,
      `    ALTER TABLE "${table}" RENAME COLUMN "${from}" TO "${to}";`,
      "  END IF;",
      "END $$;",
    ].join("\n");
  }

  /*
   * A new enum value. Postgres has IF NOT EXISTS for this one, so a second
   * run is a no-op. Inside the file's one transaction the value cannot be
   * *used* until it commits, which is fine: the seed's departments and house
   * vendor name no value added this way, and a migration that ever needs to
   * write one belongs after a COMMIT of its own.
   */
  if (/^ALTER TYPE .+ ADD VALUE '/.test(sql)) return sql.replace(/ ADD VALUE '/, " ADD VALUE IF NOT EXISTS '");

  // Postgres has no IF NOT EXISTS for either of these, so swallow the
  // "already there" error and let every other error still fail the run.
  if (/^CREATE TYPE /.test(sql) || /^ALTER TABLE .+ ADD CONSTRAINT /.test(sql)) {
    const body = sql.replace(/;\s*$/, "");
    return `DO $$ BEGIN\n  ${body};\nEXCEPTION WHEN duplicate_object THEN NULL;\nEND $$;`;
  }

  unhandled.push(sql.split("\n")[0].slice(0, 80));
  return sql;
}

const statementsOf = name => readFileSync(path.join(migrationsDir, name), "utf-8")
  .split("--> statement-breakpoint")
  .map(statement => statement.trim())
  .filter(Boolean);

/*
 * An index a later migration drops is never created.
 *
 * Created-then-dropped is, on any database, the same as never created — and
 * only the first can fail. `product_variants_sku_unique` is why: 0003 made SKUs
 * unique across the whole marketplace and 0033 dropped that for a per-product
 * index, because two sellers may both type "BATT-1". Re-run on a database where
 * two sellers had done exactly that, the file tried to rebuild the old index
 * first, failed on the duplicate, and — being one transaction — applied
 * nothing at all, new migrations included. A clean database never showed it;
 * a database being used for what the schema now allows did.
 *
 * Only a drop that comes *after* the create counts, so an index dropped and
 * then made again under the same name is still made.
 */
const ordered = migrations.flatMap(name => statementsOf(name).map(sql => ({ name, sql })));
const indexName = sql => sql.match(/^CREATE (?:UNIQUE )?INDEX "([^"]+)"/)?.[1] ?? null;
const droppedLater = new Set();
ordered.forEach(({ sql }, position) => {
  const created = indexName(sql);
  if (!created) return;
  if (ordered.slice(position + 1).some(later => later.sql.startsWith(`DROP INDEX "${created}"`))) droppedLater.add(position);
});

/*
 * And a table a later migration drops is never created, altered or indexed.
 *
 * Same reasoning, and found the same way — on a real database rather than a
 * clean one. 0037 made the shopper–store messaging tables and 0069 dropped
 * them, so the file created both, added their keys and indexes, and dropped
 * them again; on the owner's Supabase project one of those statements in
 * between failed with `relation "conversation_messages" does not exist`, and
 * the whole run applied nothing. Every statement that names the table before
 * its drop — creating it, altering it, indexing it, a key from another table
 * pointing at it — is left out, and only the `DROP TABLE IF EXISTS` stays, to
 * take it off a database that still has it. A table dropped and then made
 * again under the same name keeps everything after the drop.
 */
const tableDrops = new Map();
ordered.forEach(({ sql }, at) => {
  const dropped = sql.match(/^DROP TABLE "([^"]+)"/)?.[1];
  if (dropped) tableDrops.set(dropped, [...(tableDrops.get(dropped) ?? []), at]);
});
const tableNamed = sql =>
  sql.match(/^(?:CREATE TABLE|ALTER TABLE) "([^"]+)"/)?.[1]
  ?? sql.match(/^CREATE (?:UNIQUE )?INDEX "[^"]+" ON "([^"]+)"/)?.[1]
  ?? null;
const referencesTable = (sql, table) => sql.includes(`REFERENCES "public"."${table}"`);
const goneLater = new Map();
ordered.forEach(({ sql }, at) => {
  if (/^DROP TABLE /.test(sql)) return;
  for (const [table, drops] of tableDrops) {
    if (!drops.some(drop => drop > at)) continue;
    if (tableNamed(sql) === table || referencesTable(sql, table)) goneLater.set(at, table);
  }
});

let position = 0;
const sections = migrations.map(name => {
  const body = statementsOf(name)
    .map(sql => {
      const at = position++;
      if (goneLater.has(at)) {
        return `-- ${goneLater.get(at)}: dropped by a later migration, so never created, altered or indexed here.`;
      }
      return droppedLater.has(at)
        ? `-- ${indexName(sql)}: created here and dropped by a later migration, so never created.`
        : idempotent(sql);
    })
    .join("\n");
  return `\n-- ===== ${name} =====\n${body}\n`;
});

/* Read the departments out of the TypeScript rather than re-listing them:
   the point of the file living in `shared` is that there is one copy. */
const departmentsSource = readFileSync(path.join(root, "Shared/commerce/departments.ts"), "utf-8");
/* `[^}]*` after the position, rather than an immediate `}`: the four fields
   this seed needs are not the only ones a department carries. It gained a
   label, an icon and a tint when the departments got icons, and a pattern that
   insisted `position` came last stopped matching — which the guard below
   caught, but only because somebody ran the generator. `bootstrap.test.ts`
   runs this parse now so a fifth field cannot break it quietly. */
const departments = [...departmentsSource.matchAll(
  /\{\s*slug:\s*"([^"]+)",\s*name:\s*"([^"]+)",\s*nameAr:\s*"([^"]+)",\s*position:\s*(\d+)[^}]*\}/g,
)].map(([, slug, name, nameAr, position]) => ({ slug, name, nameAr, position }));

if (departments.length === 0) {
  throw new Error("No departments parsed from Shared/commerce/departments.ts — refusing to write an empty seed.");
}

const seed = `
-- ===== seed: departments and the house vendor =====
-- Mirrors \`pnpm db:seed\`. Safe to run again: both inserts skip a row that is
-- already there, so re-running after adding a department disturbs nothing.
--
-- Deliberately no products. A product needs a vendor to own it and a
-- department to be found in; the catalog itself is yours to add at /admin.

INSERT INTO categories (slug, name, name_ar, position) VALUES
${departments.map(d => `  (${quote(d.slug)}, ${quote(d.name)}, ${quote(d.nameAr)}, ${d.position})`).join(",\n")}
ON CONFLICT (slug) DO NOTHING;

-- NetLet sells its own stock as well as its vendors'. Something has to own a
-- product before a product can exist, so this vendor is that owner: approved,
-- auto-publishing (an admin reviewing their own listings teaches nothing), and
-- on zero commission because NetLet takes nothing from itself.
INSERT INTO vendors (slug, name, name_ar, status, auto_publish, commission_percent) VALUES
  ('netlet', 'NetLet', 'نتلت', 'approved', true, '0.00')
ON CONFLICT (slug) DO NOTHING;

-- ===== did the whole file run? =====
--
-- A paste that gets cut short fails *silently*, and it always loses the end of
-- the file — which is where the newest migrations are. That is the worst
-- possible half to lose: the schema the deployed code has just started
-- selecting from. It has happened three times now, and the symptom arrives
-- later and somewhere else, as "products will not load".
--
-- This COMMIT is what makes that harmless. Everything above it is one
-- transaction, so a truncated paste never reaches here and nothing is
-- applied — the database stays exactly as it was rather than becoming a
-- half-way state that matches neither the old code nor the new.
COMMIT;

-- And the row below is how you know it got here. It runs after the commit, so
-- it is the last result the SQL editor shows: if you can read it, everything
-- above it ran and was kept. If you cannot see it, nothing was applied —
-- scroll to the end of what you pasted, and paste the file again in full.
SELECT
  'bootstrap complete' AS status,
  ${migrations.length} AS migrations_in_this_file,
  (SELECT count(*) FROM information_schema.tables WHERE table_schema = 'public') AS tables,
  (SELECT count(*) FROM categories) AS departments;
`;

const out = path.join(root, "docs/supabase-bootstrap.sql");
writeFileSync(out, header + sections.join("") + seed);
if (unhandled.length) {
  // Loud, because a statement that slipped through is a file that claims to
  // be re-runnable and is not.
  console.error(`\nNot made idempotent — teach idempotent() these shapes:`);
  for (const line of unhandled) console.error(`  ${line}`);
  process.exit(1);
}

console.log(`docs/supabase-bootstrap.sql — ${migrations.length} migrations, ${departments.length} departments, every statement idempotent`);
