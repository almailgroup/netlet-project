export const messages: Record<LocaleCode, Record<MessageKey, string>> = { en, ar };

/**
 * Looks up a message and substitutes `{placeholders}`.
 *
 * Falls back to English rather than showing the raw key: a missing translation
 * should read as an untranslated word, not as `product.addToCart`.
 */
export function translate(
  locale: LocaleCode,
  key: MessageKey,
  values?: Record<string, string | number>,
): string {
  const template = messages[locale]?.[key] ?? en[key] ?? key;
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in values ? String(values[name]) : whole,
  );
}

/** Arabic is right-to-left; everything else here is not. */
export function directionFor(locale: LocaleCode): "rtl" | "ltr" {
  return locale === "ar" ? "rtl" : "ltr";
}

/**
 * Whether a string is one of this dictionary's keys.
 *
 * The server answers a failed sign-in with a key rather than a sentence, so the
 * shopper reads the refusal in their own language. Anything else — a Zod
 * validation message, a configuration error — is passed through untouched
 * rather than swallowed.
 */
export function isMessageKey(value: string): value is MessageKey {
  return value in en;
}
