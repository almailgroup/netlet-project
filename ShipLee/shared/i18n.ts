export const DICTIONARY: Record<Lang, Record<Key, string>> = { en, ar };

/** Sentences whose number moves, by the plural band `Intl.PluralRules` names. */
type Forms = Partial<Record<Intl.LDMLPluralRule, string>> & { other: string };
export const PLURALS = {
  pieces: {
    en: { one: "{count} piece", other: "{count} pieces" },
    ar: { one: "قطعة واحدة", two: "قطعتان", few: "{count} قطع", many: "{count} قطعة", other: "{count} قطعة" },
  },
  shipments: {
    en: { one: "{count} shipment", other: "{count} shipments" },
    ar: { zero: "لا توجد شحنات", one: "شحنة واحدة", two: "شحنتان", few: "{count} شحنات", many: "{count} شحنة", other: "{count} شحنة" },
  },
} satisfies Record<string, Record<Lang, Forms>>;
export type PluralKey = keyof typeof PLURALS;

export type Params = Record<string, string | number>;

function fill(text: string, params: Params): string {
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole));
}

export function translate(lang: Lang, key: Key, params: Params = {}): string {
  return fill(DICTIONARY[lang][key], params);
}

export function plural(lang: Lang, key: PluralKey, count: number): string {
  const forms: Forms = PLURALS[key][lang];
  const band = new Intl.PluralRules(lang).select(count);
  return fill(forms[band] ?? forms.other, { count: formatCount(count) });
}

/** Counts in Latin digits on both pages, as NetLet writes them. */
export function formatCount(count: number): string {
  return new Intl.NumberFormat("en-US").format(count);
}
